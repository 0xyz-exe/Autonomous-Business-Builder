"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { api } from "@/lib/api";
import type { BusinessProjectSummary } from "@/types";

const STATUS_STYLE: Record<string, { color: string; bg: string; label: string }> = {
  completed: { color: "#00D4AA", bg: "rgba(0,212,170,0.12)", label: "✓ Completed" },
  running: { color: "#6C63FF", bg: "rgba(108,99,255,0.12)", label: "⚡ Running" },
  pending: { color: "#FFB347", bg: "rgba(255,179,71,0.12)", label: "⏳ Pending" },
  failed: { color: "#FF6584", bg: "rgba(255,101,132,0.12)", label: "✗ Failed" },
};

function formatDate(iso: string) {
  return new Date(iso).toLocaleString(undefined, {
    dateStyle: "medium",
    timeStyle: "short",
  });
}

export default function ProjectsPage() {
  const [projects, setProjects] = useState<BusinessProjectSummary[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    api
      .listProjects()
      .then(setProjects)
      .catch((err: unknown) => {
        setError(err instanceof Error ? err.message : "Failed to load projects");
      })
      .finally(() => setLoading(false));
  }, []);

  return (
    <div style={{ minHeight: "100vh", paddingTop: 100, paddingBottom: 60 }}>
      <div style={{ maxWidth: 900, margin: "0 auto", padding: "0 24px" }}>
        <div style={{ marginBottom: 40 }}>
          <h1
            style={{
              fontSize: "clamp(28px, 4vw, 40px)",
              fontWeight: 800,
              letterSpacing: "-0.02em",
              marginBottom: 8,
            }}
          >
            Your <span className="gradient-text">Projects</span>
          </h1>
          <p style={{ color: "#8888AA", fontSize: 15 }}>
            Resume or review business packages generated by the agent pipeline.
          </p>
        </div>

        <div style={{ marginBottom: 24 }}>
          <Link href="/new-business" className="btn-primary" style={{ textDecoration: "none", display: "inline-block" }}>
            + New Business
          </Link>
        </div>

        {loading && (
          <p style={{ color: "#8888AA", textAlign: "center", padding: 48 }}>Loading projects...</p>
        )}

        {error && (
          <div
            className="glass-card"
            style={{ padding: 24, color: "#FF6584", marginBottom: 24 }}
          >
            ⚠️ {error}
            <p style={{ color: "#8888AA", fontSize: 13, marginTop: 12 }}>
              Make sure the backend is running at{" "}
              {process.env.NEXT_PUBLIC_API_URL || "http://localhost:8000"}
            </p>
          </div>
        )}

        {!loading && !error && projects.length === 0 && (
          <div
            className="glass-card"
            style={{ padding: 48, textAlign: "center" }}
          >
            <div style={{ fontSize: 40, marginBottom: 16 }}>📂</div>
            <h2 style={{ fontSize: 20, fontWeight: 700, marginBottom: 8 }}>No projects yet</h2>
            <p style={{ color: "#8888AA", marginBottom: 24 }}>
              Create your first business package to see it here.
            </p>
            <Link href="/new-business" className="btn-primary" style={{ textDecoration: "none" }}>
              Start Building →
            </Link>
          </div>
        )}

        {!loading && projects.length > 0 && (
          <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
            {projects.map((p) => {
              const st = STATUS_STYLE[p.status] ?? STATUS_STYLE.pending;
              return (
                <Link
                  key={p.id}
                  href={`/results/${p.id}`}
                  className="glass-card"
                  style={{
                    display: "block",
                    padding: "20px 24px",
                    textDecoration: "none",
                    transition: "border-color 0.2s",
                  }}
                >
                  <div style={{ display: "flex", justifyContent: "space-between", gap: 16, flexWrap: "wrap" }}>
                    <div style={{ flex: 1, minWidth: 200 }}>
                      <p
                        style={{
                          color: "#F0F0FF",
                          fontWeight: 600,
                          fontSize: 15,
                          marginBottom: 8,
                          display: "-webkit-box",
                          WebkitLineClamp: 2,
                          WebkitBoxOrient: "vertical",
                          overflow: "hidden",
                        }}
                      >
                        {p.business_idea}
                      </p>
                      <p style={{ fontSize: 13, color: "#8888AA" }}>
                        🎯 {p.target_market} · 🌍 {p.country} · 💰 {p.budget}
                      </p>
                    </div>
                    <div style={{ textAlign: "right" }}>
                      <span
                        style={{
                          display: "inline-block",
                          padding: "4px 12px",
                          borderRadius: 20,
                          fontSize: 12,
                          fontWeight: 600,
                          color: st.color,
                          background: st.bg,
                          marginBottom: 8,
                        }}
                      >
                        {st.label}
                      </span>
                      <div style={{ fontSize: 12, color: "#555577" }}>{formatDate(p.created_at)}</div>
                    </div>
                  </div>
                </Link>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
